import {
  pgTable,
  uuid,
  text,
  integer,
  boolean,
  timestamp,
  pgEnum,
  jsonb,
  real,
  index,
  primaryKey,
} from "drizzle-orm/pg-core";
import { users } from "./user.model";
import { customType } from "drizzle-orm/pg-core";

/** Postgres bigint kept as a decimal string in JS (a 64-bit value doesn't fit a JS number, and BigInt can't go in JSON). */
const bigintText = customType<{ data: string; driverData: string }>({
  dataType: () => "bigint",
  fromDriver: (v) => String(v),
  toDriver: (v) => v,
});


export const wallpaperStatusEnum = pgEnum("wallpaper_status", [
  "pending",
  "approved",
  "rejected",
  /** uploader's account is disabled — back to "approved" when re-enabled */
  "hidden",
]);

export const wallpaperFormatEnum = pgEnum("wallpaper_format", [
  "jpeg",
  "png",
  "webp",
  "avif",
]);

// define vector type for pgvector
const vector = (name: string, dimensions: number) =>
  customType<{ data: number[] }>({
    dataType() {
      return `vector(${dimensions})`;
    },
    toDriver(value: number[]): string {
      return `[${value.join(",")}]`;
    },
    fromDriver(value: unknown): number[] {
      if (typeof value === "string") {
        return value
          .replace("[", "")
          .replace("]", "")
          .split(",")
          .map(Number);
      }
      return value as number[];
    },
  })(name, {});

export const categories = pgTable("categories", {
  id: uuid("id").primaryKey().defaultRandom(),
  name: text("name").notNull(),
  slug: text("slug").notNull().unique(),
  description: text("description"),
  /** A few paragraphs about the collection, shown on the category page (blank line = new paragraph). */
  intro: text("intro"),
  coverImageUrl: text("cover_image_url"),
  /** Small webp of the cover (or of the most downloaded live wallpaper) for menus. */
  coverThumbUrl: text("cover_thumb_url"),
  /** The image the thumbnail was made from — a different source means it is out of date. */
  coverThumbSource: text("cover_thumb_source"),
  sortOrder: integer("sort_order").notNull().default(0),
  /** Hidden by an admin: the category and all its wallpapers are left out of every public page and list. */
  isHidden: boolean("is_hidden").notNull().default(false),
});

export const wallpapers = pgTable("wallpapers", {
  id: uuid("id").primaryKey().defaultRandom(),
  title: text("title").notNull(),
  description: text("description"),
  fileUrl: text("file_url").notNull(),
  cdnVariants: jsonb("cdn_variants"),
  blurhash: text("blurhash").notNull(),
  dominantColor: text("dominant_color").notNull(),
  palette: text("palette").array().notNull().default([]),
  width: integer("width").notNull(),
  height: integer("height").notNull(),
  fileSizeBytes: integer("file_size_bytes").notNull(),
  format: wallpaperFormatEnum("format").notNull(),
  categoryId: uuid("category_id").references(() => categories.id),
  uploaderId: uuid("uploader_id").references(() => users.id),
  tags: text("tags").array().notNull().default([]),
  isPremium: boolean("is_premium").notNull().default(false),
  isFeatured: boolean("is_featured").notNull().default(false),
  isAiGenerated: boolean("is_ai_generated").notNull().default(false),
  isMobile: boolean("is_mobile").notNull().default(false),
  downloadCount: integer("download_count").notNull().default(0),
  likeCount: integer("like_count").notNull().default(0),
  viewCount: integer("view_count").notNull().default(0),
  trendingScore: real("trending_score").notNull().default(0),
  status: wallpaperStatusEnum("status").notNull().default("pending"),
  createdAt: timestamp("created_at").notNull().defaultNow(),
  updatedAt: timestamp("updated_at").notNull().defaultNow(),
  /** CLIP visual embedding — for /:id/similar visual similarity (generated by @xenova at upload) */
  embedding: vector("embedding", 512),
  /** OpenAI text-embedding-3-small on title+description+tags — for /search semantic search */
  textEmbedding: vector("text_embedding", 512),
  /** Why moderation didn't auto-approve (shown in the admin review queue) */
  moderationReason: text("moderation_reason"),
  reviewedBy: uuid("reviewed_by").references(() => users.id),
  reviewedAt: timestamp("reviewed_at"),
  /** Set on reject; the file is deleted from R2 30 days later */
  rejectedAt: timestamp("rejected_at"),
  /** Admin's reason when rejecting (moderationReason is the automatic check's) */
  reviewNote: text("review_note"),
  /** 64-bit perceptual hash of the image (utils/phash) — finds re-uploads of the same picture. */
  phash: bigintText("phash"),
  /** Position on the home page hero (1 = first). Set only while isFeatured. */
  featuredOrder: integer("featured_order"),
}, (t) => [index("wallpapers_status_created_at_idx").on(t.status, t.createdAt)]);

/**
 * Extra categories for a wallpaper (max 2, enforced by the API). The primary category stays in
 * wallpapers.category_id; a wallpaper is listed on its primary and on each extra category page.
 */
export const wallpaperCategories = pgTable("wallpaper_categories", {
  wallpaperId: uuid("wallpaper_id").notNull().references(() => wallpapers.id, { onDelete: "cascade" }),
  categoryId: uuid("category_id").notNull().references(() => categories.id, { onDelete: "cascade" }),
  createdAt: timestamp("created_at").notNull().defaultNow(),
}, (t) => [primaryKey({ columns: [t.wallpaperId, t.categoryId] }), index("wallpaper_categories_category_idx").on(t.categoryId)]);
